package com;

public class DoWhileLoopDemo {
	public static void main(String[] args)
	{
		int x = 1;
		
		do
		{
			System.out.println(x);
			x++;
		}
		while(x<=9);
		
		System.out.println("----------------------------");
		
		int j = 5;
		do
		{
			System.out.println(j);
			j--;
		}
		while(j>=1);
	}
}
